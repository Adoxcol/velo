// Builds Velo's translation files from translator-friendly lists.
//
//   internal/i18n/locales/app/keys.json      English strings (the order)
//   tools/i18n/app/<lang>.json               translations, same order
//   -> internal/i18n/locales/app/<lang>.json {english: translation}
//
// Same for the extension (ext/), which also writes extension/i18n.js.
// Checks every line keeps the same {n} placeholders and HTML tags.
// Run from the repo root:  node tools/i18n/build.js
const fs = require("fs");
const path = require("path");

const tags = (s) => (s.match(/<\/?[a-z]+[^>]*>/g) || []).map((t) => t.replace(/\s.*>/, ">")).sort().join("");
const holes = (s) => (s.match(/\{\d\}/g) || []).sort().join("");
let failed = false;

function build(group) {
  const keysFile = `internal/i18n/locales/${group}/keys.json`;
  const keys = JSON.parse(fs.readFileSync(keysFile, "utf8"));
  const srcDir = `tools/i18n/${group}`;
  const out = {};
  for (const f of fs.readdirSync(srcDir).filter((f) => f.endsWith(".json"))) {
    const lang = f.replace(/\.json$/, "");
    const list = JSON.parse(fs.readFileSync(path.join(srcDir, f), "utf8"));
    if (list.length !== keys.length) {
      console.error(`${group}/${lang}: ${list.length} lines, expected ${keys.length}`);
      failed = true;
      continue;
    }
    const dict = {};
    keys.forEach((k, i) => {
      const v = list[i];
      if (typeof v !== "string" || !v.trim()) { console.error(`${group}/${lang} #${i + 1} empty: ${k}`); failed = true; return; }
      if (holes(k) !== holes(v)) { console.error(`${group}/${lang} #${i + 1} placeholders differ:\n  ${k}\n  ${v}`); failed = true; }
      if (tags(k) !== tags(v)) { console.error(`${group}/${lang} #${i + 1} tags differ:\n  ${k}\n  ${v}`); failed = true; }
      dict[k] = v;
    });
    out[lang] = dict;
    fs.writeFileSync(`internal/i18n/locales/${group}/${lang}.json`, JSON.stringify(dict, null, 1) + "\n");
  }
  return out;
}

build("app");
const ext = build("ext");
// The extension gets the translator plus every language in one file.
const runtime = fs.readFileSync("internal/i18n/runtime.js", "utf8");
fs.writeFileSync("extension/i18n.js",
  "// Generated by tools/i18n/build.js from tools/i18n/ext/*.json. Do not edit.\n" + runtime +
  "\nveloI18n.STRINGS = " + JSON.stringify(ext) + ";\n" +
  "veloI18n.lang = (() => { try { const l = (globalThis.chrome || globalThis.browser).i18n.getUILanguage().toLowerCase();\n" +
  "  if (l.startsWith(\"pt\")) return \"pt-BR\"; if (l.startsWith(\"zh\")) return \"zh-CN\"; const b = l.split(\"-\")[0];\n" +
  "  return veloI18n.STRINGS[b] ? b : \"en\"; } catch { return \"en\"; } })();\n" +
  "veloI18n.load(veloI18n.STRINGS[veloI18n.lang] || {});\n");
process.exitCode = failed ? 1 : 0;
