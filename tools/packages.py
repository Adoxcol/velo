#!/usr/bin/env python3
"""Writes veloctl's Homebrew formula and Scoop manifest for a release.

    python3 tools/packages.py 0.8.4 dist/ out/

Reads the SHA256SUMS-veloctl-*.txt files in dist/ and writes
out/Formula/veloctl.rb (for Adoxcol/homebrew-tap) and out/veloctl.json
(for Adoxcol/scoop-bucket). The release workflow pushes them.
"""
import json
import pathlib
import sys

REPO = "https://github.com/Adoxcol/velo"


def sums(dist):
    out = {}
    for f in pathlib.Path(dist).glob("SHA256SUMS-veloctl-*.txt"):
        for line in f.read_text().splitlines():
            h, _, name = line.partition("  ")
            if name:
                out[name.strip()] = h.strip()
    return out


def main(version, dist, out):
    s = sums(dist)
    url = lambda name: f"{REPO}/releases/download/v{version}/{name}"
    asset = lambda os_, arch, ext: f"veloctl-{version}-{os_}-{arch}.{ext}"

    def need(name):
        if name not in s:
            sys.exit(f"missing checksum for {name}")
        return s[name]

    formula = f'''# Generated by tools/packages.py in github.com/Adoxcol/velo. Do not edit.
class Veloctl < Formula
  desc "Fast, resumable, segmented downloads from the terminal"
  homepage "https://velo.adoxcol.com"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
      url "{url(asset("darwin", "arm64", "tar.gz"))}"
      sha256 "{need(asset("darwin", "arm64", "tar.gz"))}"
    end
    on_intel do
      url "{url(asset("darwin", "amd64", "tar.gz"))}"
      sha256 "{need(asset("darwin", "amd64", "tar.gz"))}"
    end
  end

  on_linux do
    on_arm do
      url "{url(asset("linux", "arm64", "tar.gz"))}"
      sha256 "{need(asset("linux", "arm64", "tar.gz"))}"
    end
    on_intel do
      url "{url(asset("linux", "amd64", "tar.gz"))}"
      sha256 "{need(asset("linux", "amd64", "tar.gz"))}"
    end
  end

  def install
    bin.install "veloctl"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/veloctl version")
  end
end
'''
    scoop = {
        "version": version,
        "description": "Velo's command-line downloader: fast, resumable, segmented downloads.",
        "homepage": "https://velo.adoxcol.com",
        "license": "MIT",
        "architecture": {
            "64bit": {
                "url": url(asset("windows", "amd64", "zip")),
                "hash": need(asset("windows", "amd64", "zip")),
            },
            "arm64": {
                "url": url(asset("windows", "arm64", "zip")),
                "hash": need(asset("windows", "arm64", "zip")),
            },
        },
        "bin": "veloctl.exe",
        "checkver": {"github": REPO},
        "autoupdate": {
            "architecture": {
                "64bit": {"url": f"{REPO}/releases/download/v$version/veloctl-$version-windows-amd64.zip"},
                "arm64": {"url": f"{REPO}/releases/download/v$version/veloctl-$version-windows-arm64.zip"},
            }
        },
    }
    o = pathlib.Path(out)
    (o / "Formula").mkdir(parents=True, exist_ok=True)
    (o / "Formula" / "veloctl.rb").write_text(formula)
    (o / "veloctl.json").write_text(json.dumps(scoop, indent=2) + "\n")
    print(f"wrote {o / 'Formula' / 'veloctl.rb'} and {o / 'veloctl.json'}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(sys.argv[1].lstrip("v"), sys.argv[2], sys.argv[3])
